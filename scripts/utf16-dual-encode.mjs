#!/usr/bin/env node
/**
 * Post-build: dual-encode Vite JS assets as UTF-16LE (.1ijs) for A/B testing.
 *
 * Mirrors the "iconv UTF-8→UTF-16 + rename to .1ijs" workflow, but keeps the
 * original UTF-8 .js files and rewrites the entry HTML to a tiny boot switcher
 * that loads .1ijs when the page is opened with ?utf16=1.
 *
 * Usage (after vite build):
 *   node scripts/utf16-dual-encode.mjs [distDir]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UTF16_EXT = '.1ijs';
const BOOT_NAME = 'utf16-boot.js';

/**
 * Protect sourceMappingURL / .js.map, then rewrite relative .js module urls to .1ijs.
 * @param {string} code
 */
export function rewriteJsImportsToUtf16(code) {
  const protectedMaps = [];
  const withPlaceholders = code.replace(/\.js\.map\b/g, (m) => {
    protectedMaps.push(m);
    return `\0MAP${protectedMaps.length - 1}\0`;
  });
  // Relative / bare asset imports ending in .js' or .js" or .js`
  const rewritten = withPlaceholders.replace(/\.js(["'`])/g, `${UTF16_EXT}$1`);
  return rewritten.replace(/\0MAP(\d+)\0/g, (_, i) => protectedMaps[Number(i)]);
}

/**
 * Encode UTF-8 source text as UTF-16LE with BOM (same idea as iconv -t UTF-16LE).
 * @param {string} text
 * @returns {Buffer}
 */
export function encodeUtf16LeWithBom(text) {
  const bom = Buffer.from([0xff, 0xfe]);
  const body = Buffer.from(text, 'utf16le');
  return Buffer.concat([bom, body]);
}

/**
 * @param {string} distDir
 */
export function dualEncodeDist(distDir) {
  const assetsDir = path.join(distDir, 'assets');
  if (!fs.existsSync(assetsDir)) {
    throw new Error(`No assets directory at ${assetsDir}`);
  }

  const jsFiles = fs
    .readdirSync(assetsDir)
    .filter((f) => f.endsWith('.js') && f !== BOOT_NAME)
    .sort();

  let encoded = 0;
  let totalUtf8 = 0;
  let totalUtf16 = 0;

  for (const file of jsFiles) {
    const abs = path.join(assetsDir, file);
    const utf8Text = fs.readFileSync(abs, 'utf8');
    const rewritten = rewriteJsImportsToUtf16(utf8Text);
    const utf16Buf = encodeUtf16LeWithBom(rewritten);
    const outName = file.replace(/\.js$/, UTF16_EXT);
    fs.writeFileSync(path.join(assetsDir, outName), utf16Buf);
    encoded += 1;
    totalUtf8 += Buffer.byteLength(utf8Text, 'utf8');
    totalUtf16 += utf16Buf.byteLength;
  }

  const indexPath = path.join(distDir, 'index.html');
  if (!fs.existsSync(indexPath)) {
    throw new Error(`Missing ${indexPath}`);
  }

  let html = fs.readFileSync(indexPath, 'utf8');
  const entryMatch = html.match(
    /<script\s+type="module"[^>]*\ssrc="(\.\/assets\/[^"]+\.js)"[^>]*><\/script>/,
  );
  if (!entryMatch) {
    throw new Error('Could not find module entry script in index.html');
  }
  const entryUtf8Rel = entryMatch[1]; // ./assets/index-HASH.js
  const entryFile = path.basename(entryUtf8Rel);
  const entryUtf16File = entryFile.replace(/\.js$/, UTF16_EXT);

  const bootSource = buildBootSource({
    entryUtf8: `./${entryFile}`,
    entryUtf16: `./${entryUtf16File}`,
  });
  fs.writeFileSync(path.join(assetsDir, BOOT_NAME), bootSource, 'utf8');

  const bootTag = `<script type="module" crossorigin src="./assets/${BOOT_NAME}"></script>`;
  html = html.replace(entryMatch[0], bootTag);
  fs.writeFileSync(indexPath, html, 'utf8');

  // Apache-friendly MIME hint for static hosts that honor .htaccess
  const htaccess = path.join(distDir, '.htaccess');
  const mimeLine =
    'AddType "application/javascript; charset=utf-16le" .1ijs\n';
  if (fs.existsSync(htaccess)) {
    const existing = fs.readFileSync(htaccess, 'utf8');
    if (!existing.includes('.1ijs')) {
      fs.writeFileSync(htaccess, existing.trimEnd() + '\n' + mimeLine, 'utf8');
    }
  } else {
    fs.writeFileSync(htaccess, mimeLine, 'utf8');
  }

  return {
    encoded,
    entryUtf8: entryFile,
    entryUtf16: entryUtf16File,
    totalUtf8,
    totalUtf16,
    ratio: totalUtf8 > 0 ? totalUtf16 / totalUtf8 : 0,
  };
}

/**
 * @param {{ entryUtf8: string, entryUtf16: string }} opts
 */
export function buildBootSource(opts) {
  // Keep this file UTF-8 and dependency-free. It is the only always-UTF-8 JS entry.
  return `/* generated by scripts/utf16-dual-encode.mjs — do not edit */
const ENTRY_UTF8 = ${JSON.stringify(opts.entryUtf8)};
const ENTRY_UTF16 = ${JSON.stringify(opts.entryUtf16)};

function readFlags() {
  const q = new URLSearchParams(location.search);
  const utf16Raw = (q.get('utf16') || '').toLowerCase();
  const utf16 = utf16Raw === '1' || utf16Raw === 'true' || utf16Raw === 'yes';
  const benchRaw = (q.get('bench') || '').toLowerCase();
  const bench =
    utf16 ||
    benchRaw === '1' ||
    benchRaw === 'true' ||
    benchRaw === 'yes';
  return { utf16, bench };
}

function scriptResourceStats(mode) {
  const entries = performance.getEntriesByType('resource') || [];
  const scripts = entries.filter((e) => {
    const n = e.name || '';
    return (
      n.includes('/assets/') &&
      (n.endsWith('.js') || n.endsWith('.1ijs') || n.includes('utf16-boot'))
    );
  });
  let transferSize = 0;
  let decodedBodySize = 0;
  let durationMs = 0;
  for (const e of scripts) {
    transferSize += e.transferSize || 0;
    decodedBodySize += e.decodedBodySize || 0;
    durationMs += e.duration || 0;
  }
  return {
    scriptCount: scripts.length,
    transferSize,
    decodedBodySize,
    resourceDurationMs: durationMs,
    names: scripts.map((e) => e.name.split('/').pop()),
  };
}

function showOverlay(report) {
  if (document.getElementById('cs-utf16-bench')) return;
  const el = document.createElement('div');
  el.id = 'cs-utf16-bench';
  el.setAttribute('role', 'status');
  Object.assign(el.style, {
    position: 'fixed',
    zIndex: '2147483646',
    right: '8px',
    bottom: '8px',
    maxWidth: 'min(360px, 92vw)',
    padding: '10px 12px',
    borderRadius: '8px',
    background: 'rgba(12, 16, 24, 0.92)',
    color: '#e8eef8',
    font: '12px/1.45 ui-monospace, SFMono-Regular, Menlo, Consolas, monospace',
    boxShadow: '0 4px 24px rgba(0,0,0,.45)',
    border: '1px solid rgba(255,255,255,.12)',
    pointerEvents: 'auto',
  });
  const kb = (n) => (n / 1024).toFixed(1) + ' KiB';
  el.innerHTML =
    '<div style="font-weight:700;margin-bottom:6px">utf16 bench</div>' +
    '<div>mode: <b>' + report.mode + '</b></div>' +
    '<div>entry: ' + report.entry + '</div>' +
    '<div>moduleReady: <b>' + report.moduleReadyMs.toFixed(1) + ' ms</b></div>' +
    '<div>scripts: ' + report.scripts.scriptCount +
      ' · xfer ' + kb(report.scripts.transferSize) +
      ' · body ' + kb(report.scripts.decodedBodySize) + '</div>' +
    (report.error
      ? '<div style="color:#ff8a80;margin-top:6px">error: ' +
        String(report.error).slice(0, 180) +
        '</div>'
      : '') +
    '<div style="opacity:.7;margin-top:8px">?utf16=1 · ?bench=1 · ?utf16=0</div>' +
    '<button type="button" id="cs-utf16-bench-close" style="margin-top:8px;cursor:pointer">dismiss</button>';
  document.documentElement.appendChild(el);
  el.querySelector('#cs-utf16-bench-close')?.addEventListener('click', () => el.remove());
}

async function main() {
  const { utf16, bench } = readFlags();
  const entry = utf16 ? ENTRY_UTF16 : ENTRY_UTF8;
  const t0 = performance.now();
  performance.mark('cs-boot-start');
  /** @type {any} */
  const report = {
    mode: utf16 ? 'utf16' : 'utf8',
    entry,
    moduleReadyMs: 0,
    scripts: { scriptCount: 0, transferSize: 0, decodedBodySize: 0, resourceDurationMs: 0, names: [] },
    error: null,
    timeOrigin: performance.timeOrigin,
  };
  try {
    await import(/* @vite-ignore */ entry);
    report.moduleReadyMs = performance.now() - t0;
    performance.mark('cs-module-ready');
  } catch (err) {
    report.error = err && err.message ? err.message : String(err);
    report.moduleReadyMs = performance.now() - t0;
    if (utf16) {
      console.warn('[utf16-bench] UTF-16 entry failed; falling back to UTF-8', err);
      const t1 = performance.now();
      try {
        await import(/* @vite-ignore */ ENTRY_UTF8);
        report.fallback = 'utf8';
        report.fallbackReadyMs = performance.now() - t1;
      } catch (err2) {
        report.fallbackError = err2 && err2.message ? err2.message : String(err2);
      }
    }
  }
  // Resource timings settle after the import graph starts; sample twice.
  report.scripts = scriptResourceStats(report.mode);
  setTimeout(() => {
    report.scripts = scriptResourceStats(report.mode);
    window.__CLIP_STACKER_UTF16_BENCH__ = report;
    if (bench) showOverlay(report);
  }, 0);
  window.__CLIP_STACKER_UTF16_BENCH__ = report;
  console.info('[utf16-bench]', report);
  if (bench) {
    if (document.body) showOverlay(report);
    else document.addEventListener('DOMContentLoaded', () => showOverlay(report), { once: true });
  }
}

main();
`;
}

function main() {
  const distDir = path.resolve(process.argv[2] || 'dist');
  console.log(`[utf16-dual] encoding assets in ${distDir} …`);
  const result = dualEncodeDist(distDir);
  console.log(
    `[utf16-dual] wrote ${result.encoded} × ${UTF16_EXT} (entry ${result.entryUtf8} → ${result.entryUtf16})`,
  );
  console.log(
    `[utf16-dual] size utf8=${(result.totalUtf8 / 1024).toFixed(1)} KiB  utf16=${(result.totalUtf16 / 1024).toFixed(1)} KiB  ratio=${result.ratio.toFixed(2)}×`,
  );
  console.log('[utf16-dual] open /?utf16=1 (and /?bench=1) to compare.');
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  try {
    main();
  } catch (err) {
    console.error('[utf16-dual] failed:', err);
    process.exit(1);
  }
}
